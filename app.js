//
// Lógica simplificada: existe uma coleção "partnumbers" com a lista mestre
// de todos os partnumbers que precisam ser contados (a lista total, usada
// como denominador da meta). A quantidade JÁ CONTADA é definida manualmente
// pelo botão "Atualizar Quantidade Contada" — o número digitado SUBSTITUI
// o total atual (não soma). A % é sempre: contados / total da lista.

// Normaliza o texto do partnumber para usar como ID de documento no Firestore
function sanitizePartId(code) {
  return code.trim().toUpperCase()
    .replace(/\//g, "-")
    .replace(/\s+/g, "_")
    .replace(/[.#$\[\]]/g, "_");
}

// Escreve em lotes de até 400 (limite do Firestore é 500 por batch)
async function commitInChunks(items, chunkSize, writerFn) {
  for (var i = 0; i < items.length; i += chunkSize) {
    var chunk = items.slice(i, i + chunkSize);
    var batch = db.batch();
    chunk.forEach(function(item) { writerFn(batch, item); });
    await batch.commit();
  }
}

async function loadPartnumbers() {
  try {
    var snap = await db.collection("partnumbers").get();
    partnumbers = [];
    snap.forEach(function(d) { partnumbers.push(Object.assign({ id: d.id }, d.data())); });

    // Primeira vez: se a coleção estiver vazia, popula com a lista inicial
    if (partnumbers.length === 0 && PARTNUMBERS_SEED.length > 0) {
      showToast("Cadastrando lista inicial de partnumbers...");
      await commitInChunks(PARTNUMBERS_SEED, 400, function(batch, code) {
        var id  = sanitizePartId(code);
        var ref = db.collection("partnumbers").doc(id);
        batch.set(ref, { code: code });
      });
      partnumbers = PARTNUMBERS_SEED.map(function(code) { return { id: sanitizePartId(code), code: code }; });
    }

    partnumbers.sort(function(a,b) { return a.code.localeCompare(b.code); });
  } catch(e) {
    console.error("loadPartnumbers:", e);
    showToast("Erro ao carregar partnumbers: " + e.message, "error");
  }
}

